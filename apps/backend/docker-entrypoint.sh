#!/bin/sh
# =============================================================================
#  Точка входа контейнера бэкенда.
#
#  Порядок обязателен: миграции ДО старта сервера. Иначе первый запрос
#  прилетает в схему, которой ещё нет.
#
#  Файл ДОЛЖЕН иметь окончания строк LF. За это отвечает .gitattributes;
#  при CRLF Alpine выдаст "no such file or directory" на этой строке.
# =============================================================================
set -e

echo "→ Применение схемы базы данных…"
# Если миграции закоммичены — накатываем их (идемпотентно, продакшн-путь).
# На чистом развёртывании без папки миграций синхронизируем схему напрямую,
# чтобы `docker compose up` работал сразу «из коробки».
if [ -d "prisma/migrations" ] && [ -n "$(ls -A prisma/migrations 2>/dev/null | grep -v migration_lock.toml)" ]; then
  npx prisma migrate deploy
else
  echo "  папка миграций пуста — синхронизация схемы через db push"
  npx prisma db push --skip-generate --accept-data-loss
fi

# Расширения, tsvector-триггер и частичные индексы применяет сам бэкенд
# при старте (PrismaService.applyPostgresExtras).

# Сид создаёт первичного администратора и структуру сайта. Повторно безопасен:
# всё через upsert. Пропускается, если явно отключён.
if [ "${RUN_SEED:-true}" = "true" ]; then
  echo "→ Инициализация данных…"
  tsx prisma/seed.ts || echo "  (сид пропущен)"
fi

echo "→ Запуск сервиса…"
exec "$@"
