import { SetMetadata } from '@nestjs/common';

export const SKIP_2FA_KEY = 'skip2fa';

/**
 * Разрешает роуту работать без включённой 2FA у администратора.
 *
 * Нужен ровно на тех эндпоинтах, что требуются, чтобы САМ путь настройки
 * 2FA был проходим: посмотреть себя, включить 2FA, сменить временный
 * пароль, выйти. На всё остальное для роли ADMIN действует принудительное
 * требование 2FA (см. JwtAuthGuard) — иначе украденный/подобранный пароль
 * администратора без включённого второго фактора даёт полный доступ,
 * хотя 2FA формально «есть в системе».
 */
export const Skip2FAEnforcement = () => SetMetadata(SKIP_2FA_KEY, true);
