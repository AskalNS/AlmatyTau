/* ============================================================================
   Транслитерация в slug.

   Живёт в contracts, а не в админке, потому что нужна обеим сторонам:
   админка предлагает адрес при вводе заголовка, бэкенд подстраховывает,
   если slug пришёл пустым.

   Казахские буквы обрабатываются отдельно от русских — при обычной
   транслитерации ә, ғ, қ, ң, ө, ұ, ү, һ, і теряются или превращаются
   в один и тот же символ, и адреса начинают конфликтовать между собой.
   ========================================================================== */

const MAP: Record<string, string> = {
  // --- казахские специфичные (должны идти до русских) ---
  ә: 'a', ғ: 'g', қ: 'k', ң: 'n', ө: 'o', ұ: 'u', ү: 'u', һ: 'h', і: 'i',

  // --- кириллица ---
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh',
  з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e',
  ю: 'yu', я: 'ya',

  // --- латиница с диакритикой (английские и заимствованные названия) ---
  á: 'a', à: 'a', â: 'a', ä: 'a', ã: 'a', å: 'a',
  é: 'e', è: 'e', ê: 'e', ë: 'e',
  í: 'i', ì: 'i', î: 'i', ï: 'i',
  ó: 'o', ò: 'o', ô: 'o', ö: 'o', õ: 'o',
  ú: 'u', ù: 'u', û: 'u', ü: 'u',
  ñ: 'n', ç: 'c', ß: 'ss',
};

/**
 * Приводит произвольный заголовок к адресу страницы.
 *
 * Кириллица в URL не используется сознательно: percent-encoding казахских
 * букв даёт нечитаемые ссылки, которые ломаются при вставке в документы,
 * письма и мессенджеры.
 *
 * @example
 *   slugify('Алматы тау кластері')      → 'almaty-tau-klasteri'
 *   slugify('Ұйымдық құрылым')          → 'uyymdyk-kurylym'
 *   slugify('Новости — 2026 год!')      → 'novosti-2026-god'
 */
export function slugify(input: string, maxLength = 100): string {
  const slug = input
    .toLowerCase()
    .trim()
    .split('')
    .map((ch) => (ch in MAP ? MAP[ch] : ch))
    .join('')
    // всё, что не латиница и не цифра, становится дефисом
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-');

  if (slug.length <= maxLength) return slug;

  // Обрезаем по границе слова, а не посередине
  const cut = slug.slice(0, maxLength);
  const lastDash = cut.lastIndexOf('-');
  return lastDash > maxLength * 0.6 ? cut.slice(0, lastDash) : cut;
}

/** Проверка без выброса исключения — для подсветки поля в админке. */
export function isValidSlug(value: string): boolean {
  return /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value) && value.length <= 160;
}
