#!/bin/bash
# =============================================================================
#  Обновление боевого сервера.
#
#  Запускать из корня репозитория на сервере:
#    ./infra/deploy.sh
#
#  Подтягивает код, пересобирает изменившиеся образы и перезапускает только
#  их — контейнеры без изменений не трогаются, простоя не возникает.
#  Миграции БД накатываются автоматически при старте backend (см. README).
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

if [ ! -f .env ]; then
  echo "ОШИБКА: .env не найден. Скопируйте .env.example и заполните значения." >&2
  exit 1
fi

echo "→ Обновление кода…"
git pull --ff-only

echo "→ Сборка и перезапуск изменившихся сервисов…"
docker compose up -d --build

echo "→ Статус сервисов:"
docker compose ps

echo "→ Очистка неиспользуемых образов…"
docker image prune -f

echo "Готово."
